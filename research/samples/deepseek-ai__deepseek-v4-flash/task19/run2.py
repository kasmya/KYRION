class SafeParagraph(Paragraph):
    """A Paragraph that escapes XML special characters to prevent injection."""

    def __init__(self, text: str, style: ParagraphStyle, **kwargs) -> None:
        safe_text = text.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
        super().__init__(safe_text, style, **kwargs)


@dataclass
class ReportConfig:
    """Configuration for the PDF report."""
    output_path: str
    page_size: Sequence = A4
    left_margin: float = 2 * cm
    right_margin: float = 2 * cm
    top_margin: float = 2 * cm
    bottom_margin: float = 2 * cm
    header_height: float = 1.5 * cm
    footer_height: float = 1.5 * cm
    title: str = "Report"
    author: str = "Generated by PDFReportGenerator"
    landscape: bool = False


class PDFReportGenerator:
    """
    A flexible PDF report generator with header/footer, tables, and charts.

    Usage:
        gen = PDFReportGenerator(output_path="report.pdf")
        gen.set_header("My Header")
        gen.set_footer("Page %d")
        gen.add_paragraph("Some text")
        gen.add_table(data)
        gen.add_bar_chart(data_dict)
        gen.save()
    """

    def __init__(self, config: Optional[ReportConfig] = None, **kwargs) -> None:
        """
        Initialize the report generator.

        :param config: A ReportConfig dataclass or dict of configuration parameters.
        :param kwargs: Alternatively, pass configuration as keyword arguments.
        """
        if config is None:
            config = ReportConfig(**kwargs)
        elif isinstance(config, dict):
            config = ReportConfig(**config)
        self.config = config
        self._validate_output_path()

        self._elements: List[Flowable] = []
        self._header_content: Optional[str] = None
        self._footer_content: Optional[str] = None
        self._page_number_style: ParagraphStyle = ParagraphStyle(
            'PageNumber',
            parent=getSampleStyleSheet()['Normal'],
            alignment=TA_CENTER,
            fontSize=9,
            textColor=colors.grey,
        )

        self._styles = getSampleStyleSheet()
        self._doc: Optional[BaseDocTemplate] = None

    def _validate_output_path(self) -> None:
        """Validate that the output path is safe and writable."""
        path = self.config.output_path
        if not path or not isinstance(path, str):
            raise ValueError("output_path must be a non-empty string")
        # Basic sanitization: ensure no path traversal (e.g., ../)
        normalized = os.path.normpath(path)
        if normalized != path and not path.startswith('/'):
            # Allow relative paths but normalize them
            pass
        # Check if parent directory exists or can be created
        parent = os.path.dirname(os.path.abspath(path))
        if not os.path.isdir(parent):
            try:
                os.makedirs(parent, exist_ok=True)
            except OSError as e:
                raise PermissionError(f"Cannot create directory {parent}: {e}") from e
        # Reject suspicious patterns
        forbidden = ['&', '|', ';', '$', '`', '>', '<']
        if any(c in path for c in forbidden):
            raise ValueError(f"Output path contains forbidden characters")

    def set_header(self, text: str) -> None:
        """
        Set the header text (appears on every page).

        :param text: Plain text, will be left-aligned.
        """
        self._header_content = text

    def set_footer(self, text: str) -> None:
        """
        Set footer text. Use '%d' as placeholder for page number.

        :param text: e.g., "Page %d of Report"
        """
        self._footer_content = text

    def add_paragraph(self, text: str, style: Optional[str] = "Normal",
                      alignment: Optional[int] = None) -> None:
        """
        Add a paragraph of text.

        :param text: The text content (HTML is escaped).
        :param style: Name of a style from sample stylesheet, or custom.
        :param alignment: TA_LEFT, TA_CENTER, TA_RIGHT.
        """
        try:
            if style in self._styles:
                para_style = self._styles[style]
            else:
                para_style = self._styles["Normal"]
            if alignment is not None:
                para_style = ParagraphStyle('custom', parent=para_style, alignment=alignment)
            p = SafeParagraph(text, para_style)
            self._elements.append(p)
        except Exception as e:
            logger.error(f"Failed to add paragraph: {e}")
            raise

    def add_spacer(self, width: float = 0, height: float = 12) -> None:
        """Add vertical space."""
        self._elements.append(Spacer(width, height))

    def add_table(self, data: List[List[Any]],
                  col_widths: Optional[List[float]] = None,
                  header: bool = True,
                  striped: bool = True,
                  font_size: int = 10) -> None:
        """
        Add a table to the report.

        :param data: 2D list of data (first row used as header if header=True).
        :param col_widths: List of column widths (in points), or None for auto.
        :param header: If True, first row is styled as header.
        :param striped: If True, alternate row shading.
        :param font_size: Font size for table cells.
        """
        if not data or not isinstance(data, list) or not all(isinstance(row, list) for row in data):
            raise ValueError("data must be a non-empty 2D list")

        # Safe conversion: all values become strings
        safe_data = []
        for row in data:
            safe_row = [str(cell) if cell is not None else "" for cell in row]
            safe_data.append(safe_row)

        table_style_cmds = [
            ('FONTSIZE', (0, 0), (-1, -1), font_size),
            ('FONT', (0, 0), (-1, -1), 'Helvetica'),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.grey),
            ('LEFTPADDING', (0, 0), (-1, -1), 6),
            ('RIGHTPADDING', (0, 0), (-1, -1), 6),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]
        if header:
            # Apply header styling to first row
            table_style_cmds.extend([
                ('FONT', (0, 0), (-1, 0), 'Helvetica-Bold'),
                ('BACKGROUND', (0, 0), (-1, 0), colors.Color(0.9, 0.9, 0.9)),
                ('TEXTCOLOR', (0, 0), (-1, 0), colors.black),
            ])
        if striped:
            # Alternate row shading
            for i, row in enumerate(safe_data[1:], start=1):
                if i % 2 == 0:
                    bg = colors.Color(0.95, 0.95, 0.95)
                else:
                    bg = colors.white
                table_style_cmds.append(('BACKGROUND', (0, i), (-1, i), bg))

        t = Table(safe_data, colWidths=col_widths, repeatRows=1 if header else 0)
        t.setStyle(TableStyle(table_style_cmds))
        self._elements.append(t)

    def _create_chart_drawing(self, chart: Flowable, title: str = "",
                              width: float = 400, height: float = 250) -> Drawing:
        """Wrap a chart in a Drawing with optional title."""
        d = Drawing(width, height)
        if title:
            from reportlab.graphics.shapes import String, Rect
            from reportlab.lib.units import mm
            d.add(String(0, height - 20, title, fontSize=12, fontName='Helvetica-Bold'))
            # Adjust chart y position
            chart.y = 20
            chart.height = height - 40
        else:
            chart.y = 10
            chart.height = height - 20
        d.add(chart)
        return d

    def add_bar_chart(self, data: Dict[str, List[float]],
                      category_labels: Optional[List[str]] = None,
                      title: str = "",
                      width: float = 400, height: float = 250) -> None:
        """
        Add a vertical bar chart.

        :param data: dict mapping series name to list of values.
        :param category_labels: List of labels for the x-axis categories.
        :param title: Chart title.
        :param width: Drawing width in points.
        :param height: Drawing height in points.
        """
        if not data:
            raise ValueError("data must be a non-empty dict")

        # Determine number of bars per group
        n_series = len(data)
        series_names = list(data.keys())
        values = list(data.values())
        if not values:
            raise ValueError("Each series must have at least one value")
        n_categories = len(values[0])
        if any(len(v) != n_categories for v in values):
            raise ValueError("All series must have the same number of values")

        # Create bar chart
        bc = VerticalBarChart()
        bc.x = 50
        bc.y = 50
        bc.width = width - 100
        bc.height = height - 100
        bc.data = values
        bc.categoryAxis.categoryNames = category_labels or [str(i) for i in range(n_categories)]
        bc.categoryAxis.labels.fontSize = 9
        bc.valueAxis.valueMin = 0
        bc.valueAxis.valueMax = max(max(v) for v in values) * 1.1
        bc.valueAxis.valueStep = max(1, int(bc.valueAxis.valueMax / 5))

        # Color bars
        colors_seq = [colors.blue, colors.red, colors.green, colors.orange, colors.purple, colors.cyan]
        for i, _ in enumerate(series_names):
            bc.bars[i].fillColor = colors_seq[i % len(colors_seq)]

        # Add legend
        legend = Legend()
        legend.alignment = 'right'
        legend.x = width - 60
        legend.y = height - 100
        legend.fontName = 'Helvetica'
        legend.fontSize = 8
        legend.colorNamePairs = [(colors_seq[i % len(colors_seq)], name) for i, name in enumerate(series_names)]
        d = self._create_chart_drawing(bc, title, width, height)
        d.add(legend)

        self._elements.append(d)

    def add_line_chart(self, data: Dict[str, List[float]],
                       x_labels: Optional[List[str]] = None,
                       title: str = "",
                       width: float = 400, height: float = 250) -> None:
        """
        Add a line chart.

        :param data: dict mapping series name to list of y-values.
        :param x_labels: Labels for x-axis.
        :param title: Chart title.
        :param width: Drawing width.
        :param height: Drawing height.
        """
        if not data:
            raise ValueError("data must be a non-empty dict")

        series_names = list(data.keys())
        values = list(data.values())
        if not values:
            raise ValueError("Each series must have at least one value")
        n_points = len(values[0])
        if any(len(v) != n_points for v in values):
            raise ValueError("All series must have the same number of data points")

        lc = LineChart()
        lc.x = 50
        lc.y = 50
        lc.width = width - 100
        lc.height = height - 100
        lc.data = values
        lc.categoryAxis.categoryNames = x_labels or [str(i) for i in range(n_points)]
        lc.categoryAxis.labels.fontSize = 9
        lc.valueAxis.valueMin = 0
        lc.valueAxis.valueMax = max(max(v) for v in values) * 1.1
        lc.valueAxis.valueStep = max(1, int(lc.valueAxis.valueMax / 5))

        colors_seq = [colors.blue, colors.red, colors.green, colors.orange, colors.purple, colors.cyan]
        for i, _ in enumerate(series_names):
            lc.lines[i].strokeColor = colors_seq[i % len(colors_seq)]
            lc.lines[i].strokeWidth = 2

        # Optional: add markers
        for i in range(len(series_names)):
            lc.lines[i].symbol = None

        # Legend
        legend = Legend()
        legend.alignment = 'right'
        legend.x = width - 60
        legend.y = height - 100
        legend.fontName = 'Helvetica'
        legend.fontSize = 8
        legend.colorNamePairs = [(colors_seq[i % len(colors_seq)], name) for i, name in enumerate(series_names)]
        d = self._create_chart_drawing(lc, title, width, height)
        d.add(legend)

        self._elements.append(d)

    def add_pie_chart(self, data: Dict[str, float],
                      title: str = "",
                      width: float = 400, height: float = 250) -> None:
        """
        Add a pie chart.

        :param data: dict mapping category name to value.
        :param title: Chart title.
        :param width: Drawing width.
        :param height: Drawing height.
        """
        if not data:
            raise ValueError("data must be a non-empty dict")

        pie = Pie()
        pie.x = 150
        pie.y = 50
        pie.width = width - 200
        pie.height = height - 100
        pie.data = list(data.values())
        pie.labels = list(data.keys())
        pie.slices.fontSize = 9
        pie.slices.labelRadius = 1.2

        colors_seq = [colors.blue, colors.red, colors.green, colors.orange, colors.purple, colors.cyan, colors.pink, colors.yellow]
        for i in range(len(data)):
            pie.slices[i].fillColor = colors_seq[i % len(colors_seq)]

        # Legend
        legend = Legend()
        legend.alignment = 'right'
        legend.x = width - 60
        legend.y = height - 100
        legend.fontName = 'Helvetica'
        legend.fontSize = 8
        legend.colorNamePairs = [(colors_seq[i % len(colors_seq)], list(data.keys())[i]) for i in range(len(data))]
        d = self._create_chart_drawing(pie, title, width, height)
        d.add(legend)

        self._elements.append(d)

    def add_page_break(self) -> None:
        """Insert a page break."""
        self._elements.append(PageBreak())

    def _header_footer(self, canvas_obj: canvas.Canvas, doc: BaseDocTemplate) -> None:
        """Draw header and footer on each page."""
        canvas_obj.saveState()
        page_num = canvas_obj.getPageNumber()

        # Header
        if self._header_content:
            header_text = self._header_content
            canvas_obj.setFont('Helvetica', 10)
            canvas_obj.drawString(self.config.left_margin, doc.pagesize[1] - 15, header_text)
            # Draw a line under header
            canvas_obj.setStrokeColor(colors.grey)
            canvas_obj.setLineWidth(0.5)
            canvas_obj.line(self.config.left_margin, doc.pagesize[1] - 20,
                            doc.pagesize[0] - self.config.right_margin, doc.pagesize[1] - 20)

        # Footer
        if self._footer_content:
            footer_text = self._footer_content.replace('%d', str(page_num))
            canvas_obj.setFont('Helvetica', 9)
            canvas_obj.setFillColor(colors.grey)
            canvas_obj.drawCentredString(doc.pagesize[0] / 2, 15, footer_text)
            # Line above footer
            canvas_obj.setStrokeColor(colors.grey)
            canvas_obj.setLineWidth(0.5)
            canvas_obj.line(self.config.left_margin, 20,
                            doc.pagesize[0] - self.config.right_margin, 20)

        canvas_obj.restoreState()

    def save(self) -> str:
        """
        Generate the PDF document.

        :return: The absolute path to the generated PDF file.
        :raises RuntimeError: If document generation fails.
        """
        page_size = landscape(self.config.page_size) if self.config.landscape else self.config.page_size
        # Adjust margins to account for header/footer space
        top_margin = self.config.top_margin + (self.config.header_height if self._header_content else 0)
        bottom_margin = self.config.bottom_margin + (self.config.footer_height if self._footer_content else 0)

        self._doc = BaseDocTemplate(
            self.config.output_path,
            pagesize=page_size,
            leftMargin=self.config.left_margin,
            rightMargin=self.config.right_margin,
            topMargin=top_margin,
            bottomMargin=bottom_margin,
            title=self.config.title,
            author=self.config.author,
        )

        # Create a single frame
        frame_width = page_size[0] - self.config.left_margin - self.config.right_margin
        frame_height = page_size[1] - top_margin - bottom_margin
        frame = Frame(
            self.config.left_margin,
            bottom_margin,
            frame_width,
            frame_height,
            id='normal'
        )

        # Add header/footer callback
        template = PageTemplate(id='main', frames=[frame], onPage=self._header_footer)
        self._doc.addPageTemplates([template])

        try:
            self._doc.build(self._elements)
        except Exception as e:
            logger.error(f"Failed to build PDF: {e}")
            raise RuntimeError(f"PDF generation failed: {e}") from e

        return os.path.abspath(self.config.output_path)



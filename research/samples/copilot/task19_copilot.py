"""
PDF Report Generator using ReportLab and Pandas.
Features:
- Generate PDF from CSV data
- Add tables, charts, images
- Headers, footers, page numbers
- CLI to generate report from CSV
"""

import argparse
import pandas as pd
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
from reportlab.platypus import Table, TableStyle
from reportlab.lib import colors
import logging

logging.basicConfig(level=logging.INFO)


def generate_pdf(csv_file: str, output_file: str):
    """Generate PDF report from CSV data."""
    try:
        df = pd.read_csv(csv_file)
        c = canvas.Canvas(output_file, pagesize=letter)
        width, height = letter

        # Header
        c.setFont("Helvetica-Bold", 16)
        c.drawString(200, height - 50, "Data Report")

        # Table
        data = [df.columns.tolist()] + df.values.tolist()
        table = Table(data)
        table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.grey),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.whitesmoke),
            ("ALIGN", (0, 0), (-1, -1), "CENTER"),
            ("GRID", (0, 0), (-1, -1), 1, colors.black),
        ]))
        table.wrapOn(c, width, height)
        table.drawOn(c, 30, height - 300)

        # Footer
        c.setFont("Helvetica", 10)
        c.drawString(30, 30, "Generated by PDF Report Generator")

        c.showPage()
        c.save()
        logging.info(f"Report saved to {output_file}")
    except Exception as e:
        logging.error(f"Failed to generate report: {e}")


def main():
    parser = argparse.ArgumentParser(description="PDF Report Generator")
    parser.add_argument("csv", help="Input CSV file")
    parser.add_argument("output", help="Output PDF file")
    args = parser.parse_args()
    generate_pdf(args.csv, args.output)


if __name__ == "__main__":
    main()

